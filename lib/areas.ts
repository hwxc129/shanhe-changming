export const AREA_ORDER = Object.freeze([...places.map(([label]) => label), "东北边境", "全国/跨区域", "境外"]);
const borderRecords = new Set(["hailanpao-massacre-1900", "jiangdong-64-villages-massacre-1900"]);
export function areasFor(id: string, location: string): string[] {
  if (borderRecords.has(id)) return ["东北边境"];
  const areas = places.filter(([, pattern]) => pattern.test(location)).map(([label]) => label);
  if (/缅甸|日本|俄国|圣彼得堡|朝鲜|新加坡|马来亚|东京湾/.test(location)) areas.push("境外");
  if (/全国|世界各地|八省|华北抗日/.test(location) || !areas.length) areas.push("全国/跨区域");
  return [...new Set(areas)];
}
